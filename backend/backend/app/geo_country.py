"""Names the country a lat/lon falls in, offline. The Python twin of frontend/src/countries.ts:
a point-in-polygon test against the Natural Earth outlines in data/countries.json (generated by
mapgen/gen-countries.js). No network call; nothing about an address leaves the server.

Country-level accuracy only (110m outlines rounded to ~11 km). Open ocean returns None."""
from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path
from typing import Optional

_NEAR_LIMIT = 30  # 3 degrees, in tenths


class _Country:
    __slots__ = ("name", "rings", "min_x", "max_x", "min_y", "max_y", "area")

    def __init__(self, name: str, rings: list[list[int]]) -> None:
        self.name = name
        self.rings = rings
        xs = [r[i] for r in rings for i in range(0, len(r), 2)]
        ys = [r[i] for r in rings for i in range(1, len(r), 2)]
        self.min_x, self.max_x, self.min_y, self.max_y = min(xs), max(xs), min(ys), max(ys)
        self.area = (self.max_x - self.min_x) * (self.max_y - self.min_y)


def _load() -> list[_Country]:
    path = Path(__file__).resolve().parent / "data" / "countries.json"
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        print(f"[geo_country] {path.name} not loaded ({exc}); countries will not be named")
        return []
    # Smallest first, so a country enclosed by another (Lesotho inside South Africa) is found first.
    return sorted((_Country(n, r) for n, r in raw), key=lambda c: c.area)


_COUNTRIES = _load()


def _in_ring(ring: list[int], x: int, y: int) -> bool:
    inside = False
    n = len(ring) // 2
    j = n - 1
    for i in range(n):
        xi, yi, xj, yj = ring[i * 2], ring[i * 2 + 1], ring[j * 2], ring[j * 2 + 1]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
            inside = not inside
        j = i
    return inside


def _nearest_sq(ring: list[int], x: int, y: int) -> int:
    best = 1 << 60
    for i in range(0, len(ring), 2):
        dx, dy = ring[i] - x, ring[i + 1] - y
        d = dx * dx + dy * dy
        if d < best:
            best = d
    return best


def _lookup(x: int, y: int) -> Optional[str]:
    for c in _COUNTRIES:
        if x < c.min_x or x > c.max_x or y < c.min_y or y > c.max_y:
            continue
        for r in c.rings:
            if _in_ring(r, x, y):
                return c.name
    best, best_d = None, _NEAR_LIMIT * _NEAR_LIMIT
    for c in _COUNTRIES:
        if x < c.min_x - _NEAR_LIMIT or x > c.max_x + _NEAR_LIMIT or y < c.min_y - _NEAR_LIMIT or y > c.max_y + _NEAR_LIMIT:
            continue
        for r in c.rings:
            d = _nearest_sq(r, x, y)
            if d < best_d:
                best_d, best = d, c.name
    return best


@lru_cache(maxsize=20_000)
def _cached(cell_lat: int, cell_lon: int) -> Optional[str]:
    # quarter-degree cells, same as the frontend
    return _lookup(round(cell_lon / 4 * 10), round(cell_lat / 4 * 10))


def country_at(lat: float, lon: float) -> Optional[str]:
    """Country name, or None for open ocean, invalid input, or (0, 0) (treated as "no location")."""
    try:
        if not (-90 <= lat <= 90 and -180 <= lon <= 180):
            return None
    except TypeError:
        return None
    if lat == 0 and lon == 0:
        return None
    return _cached(round(lat * 4), round(lon * 4))
