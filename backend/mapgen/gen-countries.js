/** One-time generator for the offline country lookup. You do not need to run
 *  this to build or run the app -- its output is already committed:
 *
 *    frontend/src/country-geo.ts       country outlines in lon/lat (Natural Earth 110m)
 *    backend/app/data/countries.json   the same outlines for the backend (anomaly.py)
 *
 *  Sightline names the SOURCE COUNTRY of each event from its coordinates, with
 *  no external geolocation service: frontend/src/countries.ts does a
 *  point-in-polygon test against these outlines. Coordinates are rounded to
 *  0.1 degree (about 11 km), plenty for "which country is this attacker in"
 *  and it keeps the file small.
 *
 *  Run:  npm install && node gen-countries.js
 */
const topojson = require("topojson-client");
const fs = require("fs");
const path = require("path");

const countries = require("world-atlas/countries-110m.json");
const fc = topojson.feature(countries, countries.objects.countries);

// Natural Earth's long names, shortened to what fits on a wall display.
const SHORT = {
  "United States of America": "United States",
  "Dem. Rep. Congo": "DR Congo",
  "Central African Rep.": "Central African Rep.",
  "Dominican Rep.": "Dominican Republic",
  "Bosnia and Herz.": "Bosnia & Herzegovina",
  "Czechia": "Czechia",
  "S. Sudan": "South Sudan",
  "W. Sahara": "Western Sahara",
  "Eq. Guinea": "Equatorial Guinea",
  "Solomon Is.": "Solomon Islands",
  "Falkland Is.": "Falkland Islands",
  "Fr. S. Antarctic Lands": "French Southern Lands",
  "N. Cyprus": "Northern Cyprus",
  "eSwatini": "Eswatini",
  "Côte d'Ivoire": "Ivory Coast",
};

const q = (v) => Math.round(v * 10);

function ringsOf(geom) {
  if (geom.type === "Polygon") return geom.coordinates;
  if (geom.type === "MultiPolygon") return geom.coordinates.flat();
  return [];
}

const out = [];
let points = 0;
for (const f of fc.features) {
  const name = SHORT[f.properties.name] || f.properties.name;
  if (!name) continue;
  const rings = [];
  for (const ring of ringsOf(f.geometry)) {
    const flat = [];
    let lx = null, ly = null;
    for (const [lon, lat] of ring) {
      const x = q(lon), y = q(lat);
      if (x === lx && y === ly) continue; // drop points that collapse together after rounding
      flat.push(x, y);
      lx = x; ly = y;
    }
    if (flat.length >= 6) { rings.push(flat); points += flat.length / 2; }
  }
  if (rings.length) out.push([name, rings]);
}

const file = path.join(__dirname, "..", "frontend", "src", "country-geo.ts");
const body =
  "// Generated by mapgen/gen-countries.js from Natural Earth 110m country data (via the\n" +
  "// world-atlas npm package). Do not hand-edit -- regenerate via mapgen/.\n" +
  "// Each country is [name, rings]; each ring is a flat list of x, y pairs in tenths of a\n" +
  "// degree (lon * 10, lat * 10). See frontend/src/countries.ts.\n" +
  "export const COUNTRY_GEO: [string, number[][]][] = " + JSON.stringify(out) + ";\n";
fs.writeFileSync(file, body);
// The backend names countries too (for the "how unusual is this?" score), from the same outlines.
const jsonFile = path.join(__dirname, "..", "backend", "app", "data", "countries.json");
fs.mkdirSync(path.dirname(jsonFile), { recursive: true });
fs.writeFileSync(jsonFile, JSON.stringify(out));
console.log(`${out.length} countries, ${points} points, ${(body.length / 1024).toFixed(0)} KB -> ${file}`);
