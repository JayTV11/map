/** One-time generator for frontend/src/country-labels.ts and
 *  frontend/src/city-labels.ts -- see README.md. You do not need to run
 *  this to build or run the app; its output is already committed.
 *
 * Countries: world-countries package (sovereign/independent states only --
 * excludes dependent territories to keep the world view from being
 * cluttered with tiny labels).
 *
 * Cities: all-the-cities package (GeoNames-derived), top N by population,
 * split into 3 tiers so the frontend can reveal more of them as the user
 * zooms in (see frontend/src/mapZoom.ts's zoom-tier classes and
 * style.css's .label-city rules) -- similar to how Google Maps shows only
 * major cities when zoomed out and fills in smaller ones on zoom.
 */
const worldCountries = require("world-countries");
const cities = require("all-the-cities");
const fs = require("fs");

const countryLabels = worldCountries
  .filter((c) => c.independent)
  .map((c) => ({
    name: c.name.common,
    lat: Number(c.latlng[0].toFixed(2)),
    lon: Number(c.latlng[1].toFixed(2)),
  }))
  .sort((a, b) => a.name.localeCompare(b.name));

const TIER1_COUNT = 40; // major world cities -- visible first, lightest zoom
const TIER2_COUNT = 200; // next tier
const TIER3_COUNT = 500; // total cap -- most zoomed-in tier

const topCities = [...cities]
  .filter((c) => c.population > 0)
  .sort((a, b) => b.population - a.population)
  .slice(0, TIER3_COUNT)
  .map((c, i) => ({
    name: c.name,
    lat: Number(c.loc.coordinates[1].toFixed(2)),
    lon: Number(c.loc.coordinates[0].toFixed(2)),
    tier: i < TIER1_COUNT ? 1 : i < TIER2_COUNT ? 2 : 3,
  }));

const header =
  "// Generated by mapgen/gen-labels.js -- do not hand-edit.\n" +
  "// Source: world-countries + all-the-cities npm packages (see mapgen/README.md).\n\n";

fs.writeFileSync(
  "../frontend/src/country-labels.ts",
  header +
    "export interface CountryLabel {\n  name: string;\n  lat: number;\n  lon: number;\n}\n\n" +
    `export const COUNTRY_LABELS: CountryLabel[] = ${JSON.stringify(countryLabels)};\n`,
);

fs.writeFileSync(
  "../frontend/src/city-labels.ts",
  header +
    "export interface CityLabel {\n  name: string;\n  lat: number;\n  lon: number;\n  tier: 1 | 2 | 3;\n}\n\n" +
    `export const CITY_LABELS: CityLabel[] = ${JSON.stringify(topCities)};\n`,
);

console.log("countries:", countryLabels.length, "cities:", topCities.length);
console.log("tier 1 sample:", topCities.slice(0, 8).map((c) => c.name));
