/** One-time generator for the state / province lines. You do not need to run this to build or run the
 *  app -- its output is already committed:
 *
 *    frontend/src/world-states.ts   internal state / province borders
 *
 *  Source: Natural Earth 50m "admin 1 - states, provinces" (public domain). At 50m it covers the United
 *  States, Canada, Russia, China, India, Indonesia, Brazil, Australia and South Africa; other countries
 *  simply show no internal lines. Same projection and 1000x500 space as gen.js.
 *
 *  Run:  npm install && node gen-states.js   (downloads the data file from GitHub)
 */
const topojson = require("topojson-client");
const { topology } = require("topojson-server");
const { presimplify, simplify } = require("topojson-simplify");
const fs = require("fs");

const W = 1000, H = 500;
const SIMPLIFY_AREA = Number(process.env.SIMPLIFY || 0.04);
const URL = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_1_states_provinces.geojson";

(async () => {
  const { geoPath, geoEquirectangular } = await import("d3-geo");
  const projection = geoEquirectangular().scale(W / (2 * Math.PI)).translate([W / 2, H / 2]).precision(0.1);
  const path = geoPath(projection).digits(1);

  const src = process.env.STATES_FILE;
  const fc = src ? JSON.parse(fs.readFileSync(src, "utf8")) : await (await fetch(URL)).json();
  const topo = simplify(presimplify(topology({ states: fc }, 1e5)), SIMPLIFY_AREA);
  // Lines between two different states of the same country (coastlines and country borders are drawn by other layers).
  const d = path(topojson.mesh(topo, topo.objects.states, (a, b) => a !== b && a.properties.admin === b.properties.admin));

  fs.writeFileSync(
    "../frontend/src/world-states.ts",
    `// Generated by mapgen/gen-states.js from Natural Earth 50m admin-1 (states, provinces) data,\n` +
      `// projected with d3-geo's equirectangular projection into a ${W}x${H} space. Do not hand-edit.\n` +
      `export const WORLD_STATES_PATH =\n  ${JSON.stringify(d)};\n`,
  );
  console.log("states path:", (d.length / 1024).toFixed(0), "KB");
})();
