/** One-time generator for the base map geometry. You do not need to run
 *  this to build or run the app -- its output is already committed:
 *
 *    frontend/src/world-path.ts     land outline (Natural Earth 110m)
 *    frontend/src/world-borders.ts  country borders (Natural Earth 110m)
 *
 *  Uses d3-geo (not hand-rolled projection math) so polygons that cross
 *  the antimeridian (Russia/Alaska, Fiji, Antarctica) are clipped
 *  correctly instead of drawing streaks across the whole map. Output is a
 *  plain equirectangular projection into a 1000x500 space -- the same
 *  space frontend/src/map.ts's project() assumes.
 *
 *  Run:  npm install && node gen.js
 */
const topojson = require("topojson-client");
const fs = require("fs");

const W = 1000, H = 500;

// "110m" is ~75 KB of land path and stays smooth under zoom/pan. "50m" has
// nicer coastlines when zoomed in but is ~10x larger (~770 KB of SVG path),
// which makes the CSS-transform zoom noticeably heavier. world-atlas also
// ships "10m"; both need the matching file names below.
const RES = "110m";

(async () => {
  const { geoPath, geoEquirectangular } = await import("d3-geo");

  const projection = geoEquirectangular().scale(W / (2 * Math.PI)).translate([W / 2, H / 2]).precision(0.1);
  const path = geoPath(projection).digits(2);

  const land = require(`world-atlas/land-${RES}.json`);
  const countries = require(`world-atlas/countries-${RES}.json`);

  const landD = path(topojson.feature(land, land.objects.land));
  // Interior borders only (a !== b drops the coastline, which the land outline already draws).
  const bordersD = path(topojson.mesh(countries, countries.objects.countries, (a, b) => a !== b));

  const note = (name) =>
    `// Generated by mapgen/gen.js from Natural Earth ${RES} ${name} data (via the\n` +
    `// world-atlas npm package), projected with d3-geo's equirectangular\n` +
    `// projection into a ${W}x${H} coordinate space, clipped at the antimeridian.\n` +
    `// Do not hand-edit -- regenerate via mapgen/.\n`;

  fs.writeFileSync("../frontend/src/world-path.ts", `${note("land")}export const WORLD_LAND_PATH =\n  ${JSON.stringify(landD)};\n`);
  fs.writeFileSync("../frontend/src/world-borders.ts", `${note("country border")}export const WORLD_BORDERS_PATH =\n  ${JSON.stringify(bordersD)};\n`);

  console.log("land path:", (landD.length / 1024).toFixed(0), "KB   borders path:", (bordersD.length / 1024).toFixed(0), "KB");
})();
